import {chromium} from '../.local/node_modules/playwright-core/index.mjs';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const artifacts=new URL('../artifacts/',import.meta.url);await fs.mkdir(artifacts,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream']});
const context=await browser.newContext({viewport:{width:1440,height:1050},permissions:['camera']});
const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));page.setDefaultTimeout(15000);
try{
 await page.goto('http://localhost:4173/');
 await page.getByRole('heading',{name:'A small movement. A whole conversation.'}).waitFor();
 await page.screenshot({path:fileURLToPath(new URL('overview.png',artifacts)),fullPage:true});
 console.log('PASS: overview renders');
 await page.getByRole('button',{name:'Explore the keyboard'}).click();
 for(const ch of 'hello')await page.getByRole('button',{name:ch,exact:true}).click();
 assert.equal(await page.locator('#message').innerText(),'hello');
 await page.getByRole('button',{name:'Delete',exact:true}).click();assert.equal(await page.locator('#message').innerText(),'hell');
 await page.getByRole('button',{name:'Undo',exact:true}).click();assert.equal(await page.locator('#message').innerText(),'hello');
 await page.getByRole('button',{name:'Speak ↗',exact:true}).click();
 await page.getByRole('button',{name:'Cancel',exact:true}).click();
 assert.equal(await page.locator('#message').innerText(),'hello');
 await page.getByRole('button',{name:'Pause',exact:true}).click();
 await page.getByRole('button',{name:'Resume',exact:true}).click();
 await page.getByRole('button',{name:'ABC',exact:true}).click();
 await page.getByRole('button',{name:'A',exact:true}).click();
 await page.getByRole('button',{name:'123 +',exact:true}).click();
 await page.getByRole('button',{name:'7',exact:true}).click();
 assert.equal(await page.locator('#message').innerText(),'helloA7');
 await page.getByRole('button',{name:'A–Z',exact:true}).click();
 await page.screenshot({path:fileURLToPath(new URL('write.png',artifacts)),fullPage:true});
 console.log('PASS: composition, editing, confirmation, pause, capitalization, numbers');
 await page.getByRole('button',{name:'Teach gestures',exact:true}).click();
 await page.getByRole('button',{name:'Create a profile',exact:true}).click();
 await page.getByLabel('Profile name').fill('Browser QA');
 await page.getByRole('button',{name:'Start my setup'}).click();
 assert.equal(await page.locator('#profile-select').inputValue(),await page.evaluate(()=>JSON.parse(localStorage.getItem('relay.profiles.v1'))[0].id));
 await page.reload();assert.match(await page.locator('#profile-select').innerText(),/Browser QA/);
 console.log('PASS: profile creation and persistent reload');
 await page.getByRole('button',{name:'Enable camera'}).click();
 await page.waitForFunction(()=>document.querySelector('#camera-pill').textContent==='ON DEVICE'||document.querySelector('#camera-pill').textContent==='NEEDS ATTENTION',{},{timeout:45000});
 assert.equal(await page.locator('#camera-pill').innerText(),'ON DEVICE',await page.locator('#camera-status').innerText());
 await page.waitForFunction(()=>document.querySelector('#signal-name').textContent==='No tracking');
 console.log('PASS: actual local MediaPipe face model loads; synthetic camera without a face rejects tracking');
 await page.getByRole('button',{name:'Turn camera off'}).click();
 await page.getByRole('button',{name:'My profiles',exact:true}).click();
 await page.getByRole('button',{name:'Export',exact:true}).click();
 await page.getByRole('button',{name:'New profile'}).click();
 await page.getByLabel('Profile name').fill('Hand QA');
 await page.getByLabel('Camera input').selectOption('hand');
 await page.getByRole('button',{name:'Start my setup'}).click();
 await page.getByRole('button',{name:'Enable camera'}).click();
 await page.waitForFunction(()=>['ON DEVICE','NEEDS ATTENTION'].includes(document.querySelector('#camera-pill').textContent),{},{timeout:45000});
 assert.equal(await page.locator('#camera-pill').innerText(),'ON DEVICE',await page.locator('#camera-status').innerText());
 console.log('PASS: actual local hand model loads');
 await page.getByRole('button',{name:'Turn camera off'}).click();
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Overview',exact:true}).click();
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Horizontal overflow on mobile');
 await page.screenshot({path:fileURLToPath(new URL('mobile.png',artifacts)),fullPage:true});
 console.log('PASS: 390px responsive layout');
 assert.deepEqual(errors,[]);console.log('PASS: no uncaught browser errors');
 await fs.writeFile(new URL('browser-results.json',artifacts),JSON.stringify({passed:true,checks:8,errors,scope:'UI and real model initialization using synthetic camera. No human recognition accuracy measured.'},null,2));
}finally{await browser.close();}

